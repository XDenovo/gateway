import { readFile, writeFile } from 'node:fs/promises'

const schemaPath = new URL('../src/db/auth-schema.ts', import.meta.url)
let source = await readFile(schemaPath, 'utf8')

const pgCoreImport =
  /import \{ (?<imports>[^}]+) \} from ['"]drizzle-orm\/pg-core['"];?/
const match = pgCoreImport.exec(source)

if (!match?.groups?.imports) {
  throw new Error(
    'Better Auth schema did not contain the expected pg-core import'
  )
}

const imports = match.groups.imports
  .split(',')
  .map((value) => value.trim())
  .filter((value) => value !== 'pgTable')

if (imports.length === match.groups.imports.split(',').length) {
  throw new Error('Better Auth schema did not import pgTable as expected')
}

source = source.replace(
  pgCoreImport,
  `import { ${['pgSchema', ...imports].join(', ')} } from 'drizzle-orm/pg-core'`
)
source = source.replaceAll('pgTable(', 'authSchema.table(')

const firstExport = source.indexOf('export const ')
if (firstExport === -1) {
  throw new Error('Better Auth schema did not contain an exported table')
}

source = `${source.slice(0, firstExport)}// Generated by the pinned Better Auth CLI and namespaced by scripts/use-auth-schema.mjs.\nexport const authSchema = pgSchema('auth')\n\n${source.slice(firstExport)}`

await writeFile(schemaPath, source)
